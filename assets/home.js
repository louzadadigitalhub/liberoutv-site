var steps = $$(".tour-step"), shots = $$("#tourShots img"), dots = $$("#tourDots i");
function showShot(n) {
  steps.forEach(function (s, i) { s.classList.toggle("on", i === n); });
  shots.forEach(function (s, i) { s.classList.toggle("on", i === n); });
  dots.forEach(function (s, i) { s.classList.toggle("on", i === n); });
}
if ("IntersectionObserver" in window) {
  var tourIO = new IntersectionObserver(function (entries) {
    entries.forEach(function (en) { if (en.isIntersecting) showShot(+en.target.getAttribute("data-shot")); });
  }, { rootMargin: "-45% 0px -45% 0px" });
  steps.forEach(function (s) { tourIO.observe(s); });
  var revealIO = new IntersectionObserver(function (entries) {
    entries.forEach(function (en) { if (en.isIntersecting) { en.target.classList.add("in"); revealIO.unobserve(en.target); } });
  }, { rootMargin: "0px 0px -12% 0px" });
  $$(".rv").forEach(function (el) { revealIO.observe(el); });
} else {
  $$(".rv").forEach(function (el) { el.classList.add("in"); });
}

/* ---------- topo: a TV se endireita enquanto a pagina rola ---------- */
var nav = $("#nav"), tv = $("#heroTv"), ticking = false;
function onScroll() {
  ticking = false;
  var y = window.scrollY || 0;
  nav.classList.toggle("solid", y > 12);
  if (reduce || !tv) return;
  var p = Math.min(1, Math.max(0, y / (window.innerHeight * .7)));
  var e = 1 - Math.pow(1 - p, 3);
  tv.style.setProperty("--tilt", (22 * (1 - e)).toFixed(2) + "deg");
  tv.style.setProperty("--sc", (.92 + .08 * e).toFixed(4));
}
window.addEventListener("scroll", function () { if (!ticking) { ticking = true; requestAnimationFrame(onScroll); } }, { passive: true });

document.documentElement.className += " js";
$("#btnEn").addEventListener("click", function () { chooseLang("en"); });
$("#btnPt").addEventListener("click", function () { chooseLang("pt"); });
applyLang((function () {
  var saved = null;
  try { saved = localStorage.getItem("liberou-lang"); } catch (e) {}
  if (saved) return saved;
  return /^pt/i.test(navigator.language || "") ? "pt" : "en";
})());

/* ---------- efeitos: barra de progresso, luz que segue o mouse, brilho nos blocos ---------- */
var bar = document.getElementById("progress"), hero = document.getElementById("top");
function onProgress() {
  var h = document.documentElement.scrollHeight - window.innerHeight;
  bar.style.setProperty("--p", h > 0 ? Math.min(1, (window.scrollY || 0) / h).toFixed(4) : 0);
}
window.addEventListener("scroll", function () { requestAnimationFrame(onProgress); }, { passive: true });
onProgress();
if (!reduce && window.matchMedia("(pointer: fine)").matches) {
  var mq = null;
  hero.addEventListener("pointermove", function (e) {
    if (mq) return;
    mq = requestAnimationFrame(function () {
      mq = null;
      var r = hero.getBoundingClientRect();
      hero.style.setProperty("--mx", (e.clientX - r.left) + "px");
      hero.style.setProperty("--my", (e.clientY - r.top) + "px");
    });
  });
  $$(".spot").forEach(function (el) {
    el.addEventListener("pointermove", function (e) {
      var r = el.getBoundingClientRect();
      el.style.setProperty("--mx", (e.clientX - r.left) + "px");
      el.style.setProperty("--my", (e.clientY - r.top) + "px");
    });
  });
}
onScroll();
requestAnimationFrame(function () { requestAnimationFrame(function () { $("#top").classList.add("ready"); }); });
