var bands = $$(".band").map(function (el, i, all) {
  var a = Number(el.getAttribute("data-a")), b = Number(el.getAttribute("data-b"));
  return {
    el: el, a: a, b: b, first: i === 0, last: i === all.length - 1,
    ramp: Number(el.getAttribute("data-ramp")) || Math.min(0.025, (b - a) * 0.35),
    op: -1, k: -1, on: false
  };
});

var target = 0, shown = 0, rafId = null, lastTick = 0;
var heroOnScreen = true, scrubOn = false, heroReady = false, videoFailed = false;
var seekBusy = false, pendingTime = null;
var loadStart = 0, loadK = 0, cueOff = false, lastEnd = -1;

function timeAt(p) {
  for (var i = 1; i < TMAP.length; i++) {
    if (p <= TMAP[i][0]) {
      var a = TMAP[i - 1], b = TMAP[i];
      return a[1] + (b[1] - a[1]) * (p - a[0]) / (b[0] - a[0]);
    }
  }
  return TMAP[TMAP.length - 1][1];
}
function heroProgress() {
  var range = hero.offsetHeight - stage.offsetHeight;
  return range > 0 ? clamp(-hero.getBoundingClientRect().top / range, 0, 1) : 0;
}

function requestSeek(time) {
  if (!video.duration) return;
  if (seekBusy) { pendingTime = time; return; }
  seekBusy = true;
  video.currentTime = Math.min(time, video.duration - 0.02);
}
video.addEventListener("seeked", function () {
  seekBusy = false;
  if (pendingTime !== null) {
    var time = pendingTime;
    pendingTime = null;
    requestSeek(time);
  }
});
video.addEventListener("error", function () {
  seekBusy = false;
  pendingTime = null;
  failVideo();
});

function updateCaptions(p) {
  bands.forEach(function (b) {
    var f = Math.min(0.02, (b.b - b.a) / 3);
    var op = (b.first ? 1 : smoothstep(p, b.a, b.a + f)) * (b.last ? 1 : 1 - smoothstep(p, b.b - f, b.b));
    var k = clamp((p - b.a) / b.ramp, 0, 1);
    if (b.first) k = Math.max(k, loadK);
    if (Math.abs(op - b.op) > 0.004 || ((op === 0 || op === 1) && op !== b.op)) {
      b.op = op;
      b.el.style.opacity = op.toFixed(3);
      if ((op > 0.001) !== b.on) {
        b.on = op > 0.001;
        b.el.classList.toggle("on", b.on);
      }
    }
    if (Math.abs(k - b.k) > 0.008 || ((k === 0 || k === 1) && k !== b.k)) {
      b.k = k;
      b.el.style.setProperty("--k", k.toFixed(3));
    }
  });
  if ((p > 0.03) !== cueOff) {
    cueOff = p > 0.03;
    cue.classList.toggle("off", cueOff);
  }
  if (videoFailed) {
    /* sem video, o quadro final entra por cima do primeiro e a jornada segue */
    var end = smoothstep(p, 0.62, 0.78);
    if (Math.abs(end - lastEnd) > 0.01 || ((end === 0 || end === 1) && end !== lastEnd)) {
      lastEnd = end;
      stage.style.setProperty("--end", end.toFixed(2));
    }
  }
}

function tick(now) {
  var dt = Math.min(100, now - (lastTick || now));
  lastTick = now;
  shown += (target - shown) * (1 - Math.pow(1 - 0.16, dt / 16.667));
  if (loadK < 1) loadK = clamp((now - loadStart - 250) / 1100, 0, 1);
  if (Math.abs(target - shown) < 0.0005 && loadK >= 1) {
    shown = target;
    rafId = null;
    lastTick = 0;
  } else {
    rafId = requestAnimationFrame(tick);
  }
  requestSeek(timeAt(shown));
  updateCaptions(shown);
}
function onScroll() {
  target = heroProgress();
  if (rafId === null && heroOnScreen) rafId = requestAnimationFrame(tick);
}

function failVideo() {
  if (videoFailed) return;
  videoFailed = true;
  if (ring.parentNode) ring.parentNode.removeChild(ring);
  $("#ending").style.backgroundImage = "url('" + ENDING_URL + "')";
  stage.classList.add("video-failed");
  updateCaptions(shown);
}
function loadHeroBlob() {
  var ctrl = new AbortController();
  var watchdog = setTimeout(function () { ctrl.abort(); }, 20000);
  return fetch(VIDEO_URL, { priority: "low", signal: ctrl.signal }).then(function (res) {
    if (!res.ok || !res.body) throw new Error("video");
    var total = Number(res.headers.get("Content-Length")) || VIDEO_BYTES;
    var reader = res.body.getReader(), chunks = [], got = 0, lastRing = 0;
    function pump() {
      return reader.read().then(function (step) {
        if (step.done) return;
        clearTimeout(watchdog);
        watchdog = setTimeout(function () { ctrl.abort(); }, 20000);
        chunks.push(step.value);
        got += step.value.length;
        var frac = Math.min(1, got / total), now = performance.now();
        if (now - lastRing > 100 || frac === 1) {
          lastRing = now;
          ring.style.setProperty("--ld", Math.round(126 * (1 - frac)));
        }
        return pump();
      });
    }
    return pump().then(function () {
      clearTimeout(watchdog);
      ring.style.setProperty("--ld", 0);
      video.src = URL.createObjectURL(new Blob(chunks, { type: "video/mp4" }));
      video.load();
      video.addEventListener("canplay", function () {
        requestSeek(timeAt(shown));
        stage.classList.add("video-ready");
      }, { once: true });
    });
  });
}
var blobStarted = false;
function startBlobFetch() {
  if (blobStarted) return;
  blobStarted = true;
  loadHeroBlob().catch(failVideo);
}
