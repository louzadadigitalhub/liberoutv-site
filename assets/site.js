var DEVICES = ["samsung", "lg", "roku", "android", "appletv", "windows", "mac", "ios"];
var currentDev = "samsung";
var tabs = $$("#tvList [role='tab']"), panel = $("#tvPanel"), focusRing = $("#focus");

function renderStores() {
  tabs.forEach(function (tab) {
    var st = $(".st", tab), state = STORES[tab.getAttribute("data-dev")];
    st.textContent = t(state);
    st.classList.toggle("is-live", state !== "soon");
  });
}
function leadKey(dev) {
  var state = STORES[dev];
  if (state === "download") return "leadDownload";
  if (DIRECT[dev] && state === "live" && LINKS[dev]) return "leadLiveLink";
  if (DIRECT[dev]) return state === "live" ? "leadLiveDirect" : "leadSoonDirect";
  return state === "live" ? "leadLive" : "leadSoon";
}
function positionFocus() {
  var tab = $("#tab-" + currentDev);
  focusRing.style.setProperty("--fy", tab.offsetTop + "px");
  focusRing.style.setProperty("--fh", tab.offsetHeight + "px");
}
function renderDevice(dev, animate) {
  currentDev = dev;
  tabs.forEach(function (tab) {
    var sel = tab.getAttribute("data-dev") === dev;
    tab.setAttribute("aria-selected", sel ? "true" : "false");
    tab.setAttribute("tabindex", sel ? "0" : "-1");
  });
  positionFocus();
  if (animate) panel.classList.add("out");
  panel.setAttribute("aria-labelledby", "tab-" + dev);
  $("#pnName").innerHTML = $("#tab-" + dev + " .nm").innerHTML;
  $("#pnLead").textContent = t(leadKey(dev));
  /* os passos do download (D) valem enquanto a loja nao publica; depois, os da loja (S) */
  var path = STORES[dev] === "download" ? "D" : "S";
  $$("#pnSteps li").forEach(function (li, i) { li.textContent = t(dev + path + (i + 1)); });
  var link = $("#pnLink");
  link.hidden = !LINKS[dev];
  if (LINKS[dev]) link.setAttribute("href", LINKS[dev]);
  if (animate) {
    void panel.offsetWidth;
    panel.classList.remove("out");
  }
}
function selectDevice(dev, moveFocus) {
  if (dev !== currentDev) renderDevice(dev, true);
  if (moveFocus) $("#tab-" + dev).focus();
}
tabs.forEach(function (tab) {
  var dev = tab.getAttribute("data-dev");
  tab.addEventListener("click", function () { selectDevice(dev, false); });
  tab.addEventListener("pointerenter", function (e) {
    if (e.pointerType === "mouse") selectDevice(dev, false);
  });
});
$("#tvList").addEventListener("keydown", function (e) {
  var i = DEVICES.indexOf(currentDev), next = -1;
  if (e.key === "ArrowDown" || e.key === "ArrowRight") next = (i + 1) % DEVICES.length;
  else if (e.key === "ArrowUp" || e.key === "ArrowLeft") next = (i + DEVICES.length - 1) % DEVICES.length;
  else if (e.key === "Home") next = 0;
  else if (e.key === "End") next = DEVICES.length - 1;
  if (next < 0) return;
  e.preventDefault();
  selectDevice(DEVICES[next], true);
});

