function rng(seed) {
  var s = seed >>> 0;
  return function () { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
}
function splitWords(el, text, seed, spread) {
  var rand = rng(seed), words = text.split(" ");
  el.textContent = "";
  words.forEach(function (word, i) {
    var w = document.createElement("span");
    w.className = "w";
    w.textContent = word;
    w.style.setProperty("--th", (i / words.length * spread + rand() * 0.06).toFixed(3));
    el.appendChild(w);
    if (i < words.length - 1) el.appendChild(document.createTextNode(" "));
  });
}
function splitChars(el, text, seed, spread) {
  var rand = rng(seed), words = text.split(" "), total = text.replace(/ /g, "").length, n = 0;
  el.textContent = "";
  words.forEach(function (word, i) {
    var w = document.createElement("span");
    w.className = "w";
    word.split("").forEach(function (ch) {
      var c = document.createElement("span");
      c.className = "c";
      c.textContent = ch;
      c.style.setProperty("--th", (n / total * spread + rand() * 0.04).toFixed(3));
      w.appendChild(c);
      n++;
    });
    el.appendChild(w);
    if (i < words.length - 1) el.appendChild(document.createTextNode(" "));
  });
}
