/* rolagem (0 a 1) para segundo do video: a camera dispara no fim da tomada,
   entao o mapa segura o comeco, corre entre as legendas, entra na tela e deixa
   o ultimo segundo (a tela do app escurecendo) para a legenda final */
var TMAP = [[0, 0], [0.30, 2.60], [0.36, 3.30], [0.62, 4.30], [0.72, 4.94], [0.78, 5.94], [1, 5.94]];

var hero = $("#top"), stage = $("#stage"), video = $("#heroVideo");
