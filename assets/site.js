function clamp(v, lo, hi) { return Math.min(hi, Math.max(lo, v)); }
function smoothstep(p, e0, e1) {
  var t = clamp((p - e0) / (e1 - e0), 0, 1);
  return t * t * (3 - 2 * t);
}

