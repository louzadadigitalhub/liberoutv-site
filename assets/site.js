var main = $("#main"), signal = $("#signal"), flow = $("#flow");
var flowLine = $(".flow-line i"), flowSteps = $$("#flow li");
var signalH = 0, pinned = false, pageRaf = null;
var last = { sig: -1, flow: -1, end: null, steps: [] };

function measure() {
  var list = $("#tvList");
  signalH = Math.round(list.getBoundingClientRect().top - main.getBoundingClientRect().top + 40);
  signal.style.setProperty("--sh", signalH + "px");
  positionFocus();
}
function setLine(key, el, v) {
  if (Math.abs(v - last[key]) > 0.004 || ((v === 0 || v === 1) && v !== last[key])) {
    last[key] = v;
    el.style.setProperty("--p", v.toFixed(3));
  }
}
function pageTick() {
  pageRaf = null;
  var vh = window.innerHeight, mainTop = main.getBoundingClientRect().top;
  if (pinned) return;

  var sig = signalH > 0 ? clamp((vh * 0.62 - mainTop) / signalH, 0, 1) : 0;
  setLine("sig", signal, sig);
  if ((sig === 1) !== last.end) { last.end = sig === 1; signal.classList.toggle("end", last.end); }

  var r = flow.getBoundingClientRect();
  var fp = clamp((vh * 0.7 - r.top - 14) / Math.max(1, r.height - 28), 0, 1);
  setLine("flow", flowLine, fp);
  flowSteps.forEach(function (li, i) {
    var on = fp * (r.height - 28) >= li.offsetTop - 6;
    if (on !== last.steps[i]) { last.steps[i] = on; li.classList.toggle("on", on); }
  });
}
function onPageScroll() {
  if (pageRaf === null) pageRaf = requestAnimationFrame(pageTick);
}
function pinToFinalStates() {
  pinned = true;
  signal.style.setProperty("--p", "1");
  signal.classList.add("end");
  flowLine.style.setProperty("--p", "1");
  flowSteps.forEach(function (li) { li.classList.add("on"); });
}
function unpinFinalStates() {
  pinned = false;
  last.sig = last.flow = -1;
  last.end = null;
  last.steps = [];
  onPageScroll();
}

